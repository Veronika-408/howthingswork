def ell(cx, cy, rx, ry, n=20, rot=0):
    c, s = math.cos(math.radians(rot)), math.sin(math.radians(rot))
    return [[round(cx + rx * math.cos(t) * c - ry * math.sin(t) * s, 1), round(cy + rx * math.cos(t) * s + ry * math.sin(t) * c, 1)]
            for t in [2 * math.pi * i / n for i in range(n)]]
def ring(cx, cy, rx, ry, w, n=40):
    """a ring as one keyhole polygon (works with any fill rule)"""
    o = ell(cx, cy, rx, ry, n); i = ell(cx, cy, rx - w, ry - w, n)
    return o + [o[0], i[0]] + i[::-1] + [i[0]]
def rect(x0, y0, x1, y1): return [[x0, y0], [x1, y0], [x1, y1], [x0, y1]]
def axis_map(S, TX, TY, a, b):
    """child points a, b -> (parent axis, child plateAxis) for child = parent placed at S, TX, TY"""
    return [[S * a[0] + TX, S * a[1] + TY], [S * b[0] + TX, S * b[1] + TY]], [a, b]

