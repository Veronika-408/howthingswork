#!/usr/bin/python3
"""Regions = hotspot outlines inside one sticker, in the sticker's own pixels.
Hand-drawn ones come from art/regions-hand.json; this adds the automatic ones, traced from the art:
  ground-city.river   the water, found by colour on the town's ground
  cell-body.inner     the jelly inside the cell membrane (membrane = outline minus inner)
  lyso-bubble.inner   the fluid inside the lysosome's membrane
and writes library/regions.js (window.REGIONS)."""
import json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from skimage import measure

HERE = Path(__file__).resolve().parent.parent
LIB = HERE / "library"
R = json.loads((HERE / "art" / "regions-hand.json").read_text()); R.pop("_note", None)


def trace(mask, tol=2.5, min_frac=.02, keep=1):
    lab, n = ndi.label(mask)
    sizes = sorted([((lab == i).sum(), i) for i in range(1, n + 1)], reverse=True)
    out = []
    for s, i in sizes[:keep]:
        if s < min_frac * mask.size * .01: continue
        m = ndi.binary_fill_holes(lab == i)
        c = max(measure.find_contours(np.pad(m, 1).astype(np.float32), .5), key=len)
        c = measure.approximate_polygon(c, tolerance=tol)
        out.append([[round(float(x) - 1, 1), round(float(y) - 1, 1)] for y, x in c])
    return out


def rgba(name):
    return np.asarray(Image.open(LIB / f"{name}.webp").convert("RGBA")).astype(np.float32)

# the river: blue-green water on the ground
g = rgba("ground-city")
r, gg, b, a = g[..., 0], g[..., 1], g[..., 2], g[..., 3]
water = (a > 128) & (b > r + 25) & (gg > r + 15) & (b > 110)
water = ndi.binary_opening(ndi.binary_closing(water, iterations=3), iterations=2)
R.setdefault("ground-city", {})["river"] = trace(water, keep=1)
# the pond is water too, but it belongs to the park, not the river

for name, px in [("cell-body", 46), ("lyso-bubble", 118)]:
    m = rgba(name)[..., 3] > 128
    m = ndi.binary_fill_holes(m)
    inner = ndi.binary_erosion(m, iterations=px)
    R.setdefault(name, {})["inner"] = trace(inner, keep=1)

(LIB / "regions.js").write_text("// generated by tools/regions.py (hand outlines from art/regions-hand.json + traced ones)\nwindow.REGIONS = " + json.dumps(R, separators=(",", ":")) + ";\n")
print({k: list(v) for k, v in R.items()})
