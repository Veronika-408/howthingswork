def R(x, y, w, h):
    return [[x, y], [x + w, y], [x + w, y + h], [x, y + h]]


def ellipse(cx, cy, rx, ry, n=16, a0=0):
    return [[round(cx + rx * math.cos(a0 + 2 * math.pi * i / n), 1), round(cy + ry * math.sin(a0 + 2 * math.pi * i / n), 1)] for i in range(n)]


def band(cx, cy, rx, ry, t, a_from, a_to, n):
    """Quads along an elliptical rim (thickness t), from angle a_from to a_to (radians)."""
    out = []
    for i in range(n):
        a, b = a_from + (a_to - a_from) * i / n, a_from + (a_to - a_from) * (i + 1) / n
        p = lambda ang, r: [round(cx + (rx + r) * math.cos(ang), 1), round(cy + (ry + r) * math.sin(ang), 1)]
        out.append([p(a, -t), p(b, -t), p(b, t), p(a, t)])
    return out


